<?php

declare(strict_types=1);

namespace CraftCms\Cms\Field\IdeHelper;

use CraftCms\Cms\Asset\Elements\Asset;
use CraftCms\Cms\Asset\Models\Volume;
use CraftCms\Cms\Cms;
use CraftCms\Cms\Element\ElementCollection;
use CraftCms\Cms\Element\Queries\EntryQuery;
use CraftCms\Cms\Entry\Elements\Entry;
use CraftCms\Cms\Entry\EntryTypes;
use CraftCms\Cms\Field\Contracts\FieldInterface;
use CraftCms\Cms\Field\Fields;
use CraftCms\Cms\Field\Matrix;
use CraftCms\Cms\FieldLayout\FieldLayout;
use CraftCms\Cms\Support\File;
use CraftCms\Cms\Support\Str;
use Illuminate\Container\Attributes\Singleton;
use Illuminate\Support\Facades\Log;
use Symfony\Component\Filesystem\Path;
use Throwable;

#[Singleton]
readonly class CustomFieldIdeHelperGenerator
{
    public function __construct(
        private Fields $fields,
        private EntryTypes $entryTypes,
    ) {}

    public function generate(): void
    {
        if (! Cms::config()->ideHelperEnabled) {
            return;
        }

        $outputPath = $this->getOutputPath();

        if (! File::makeDirectory($outputPath)) {
            return;
        }

        if (! File::exists($outputPath.'/.gitignore')) {
            File::put($outputPath.'/.gitignore', '*');
        }

        $content = $this->buildHelperContent();

        try {
            File::put($outputPath.'/custom-fields.php', $content);
        } catch (Throwable $e) {
            Log::warning('Failed to write IDE helper file: '.$e->getMessage());
        }
    }

    public function normalizeHandle(string $handle): string
    {
        return Str::studly($handle);
    }

    private function getOutputPath(): string
    {
        $path = Cms::config()->ideHelperPath;

        if (Path::isAbsolute($path)) {
            return $path;
        }

        return base_path($path);
    }

    private function buildHelperContent(): string
    {
        $elementFields = $this->collectFieldsByElement();
        $entryTypeFields = $this->collectFieldsByEntryType();
        $volumeFields = $this->collectFieldsByVolume();

        $importMap = $this->shortenTypes($elementFields, $entryTypeFields, $volumeFields);

        $lines = [
            '<?php',
            '',
            '/**',
            ' * Custom Field IDE Helper',
            ' *',
            ' * This file is auto-generated by Craft CMS. Do not edit manually.',
            ' * Regenerate via: php craft craft:ide-helper:custom-fields',
            ' *',
            ' * @generated',
            ' */',
            '',
        ];

        // Group all classes by namespace
        $namespaces = [];
        foreach ($elementFields as $elementClass => $fields) {
            if ($elementClass === Entry::class && $entryTypeFields !== []) {
                continue;
            }

            if ($elementClass === Asset::class && $volumeFields !== []) {
                continue;
            }

            $namespace = substr($elementClass, 0, (int) strrpos($elementClass, '\\'));
            $namespaces[$namespace][] = [
                'className' => class_basename($elementClass),
                'fields' => $fields,
                'see' => "\\{$elementClass}",
            ];
        }

        $this->groupSubclasses($namespaces, $entryTypeFields, 'CraftCms\Cms\Entry\Elements', 'Entry');
        $this->groupSubclasses($namespaces, $volumeFields, 'CraftCms\Cms\Asset\Elements', 'Asset');

        // Sort namespaces and classes within each namespace for deterministic output
        ksort($namespaces);
        foreach ($namespaces as &$classes) {
            usort($classes, fn (array $a, array $b) => $a['className'] <=> $b['className']);
        }
        unset($classes);

        // Render one namespace block per namespace
        foreach ($namespaces as $namespace => $classes) {
            $lines[] = "namespace {$namespace} {";

            // Collect use imports needed for this namespace block
            $namespaceImports = $this->collectImportsForNamespace($classes, $importMap, $namespace);
            foreach ($namespaceImports as $import) {
                $lines[] = "    use {$import};";
            }

            foreach ($classes as $i => $class) {
                if ($i > 0 || $namespaceImports !== []) {
                    $lines[] = '';
                }

                $hasAnnotations = $class['fields'] !== [] || isset($class['see']);

                if ($hasAnnotations) {
                    $lines[] = '    /**';

                    foreach ($class['fields'] as $handle => $type) {
                        $lines[] = "     * @property {$type} \${$handle}";
                    }

                    if (isset($class['see'])) {
                        $lines[] = '     *';
                        $lines[] = "     * @see {$class['see']}";
                    }

                    $lines[] = '     */';
                }

                $extends = isset($class['extends']) ? " extends {$class['extends']}" : '';
                $lines[] = "    class {$class['className']}{$extends} {}";
            }

            $lines[] = '}';
            $lines[] = '';
        }

        return implode("\n", $lines);
    }

    /**
     * Group subclass stubs (e.g. Entry types, Asset volumes) into the namespaces map.
     *
     * @param  array<string, list<array{className: string, fields: array<string, string>, extends?: string, see?: string}>>  $namespaces
     * @param  array<string, array<string, string>>  $classFields
     */
    private function groupSubclasses(array &$namespaces, array $classFields, string $namespace, string $parentClass): void
    {
        foreach ($classFields as $className => $fields) {
            $namespaces[$namespace][] = [
                'className' => $className,
                'fields' => $fields,
                'extends' => $parentClass,
            ];
        }
    }

    /**
     * Collect fields grouped by entry type.
     *
     * @return array<string, array<string, string>>
     */
    private function collectFieldsByEntryType(): array
    {
        $result = [];

        foreach ($this->entryTypes->getAllEntryTypes() as $entryType) {
            $layout = $entryType->getFieldLayout();

            if (! $layout) {
                continue;
            }

            $entryTypeHandle = $this->normalizeHandle($entryType->handle);
            $result[$entryTypeHandle] = $this->collectFieldsFromLayout($layout);
        }

        ksort($result);

        return $result;
    }

    /**
     * Collect fields grouped by volume for Asset elements.
     *
     * @return array<string, array<string, string>>
     */
    private function collectFieldsByVolume(): array
    {
        $result = [];

        foreach (Volume::withoutTrashed()->get() as $volume) {
            if ($volume->fieldLayoutId === null) {
                continue;
            }

            if (! $layout = $this->fields->getLayoutById($volume->fieldLayoutId)) {
                continue;
            }

            $className = $this->normalizeHandle($volume->handle).'_Asset';
            $result[$className] = $this->collectFieldsFromLayout($layout);
        }

        ksort($result);

        return $result;
    }

    /**
     * Collect all fields grouped by element class, combining fields from all layouts.
     *
     * @return array<class-string, array<string, string>>
     */
    private function collectFieldsByElement(): array
    {
        $elementFields = [];

        foreach ($this->fields->getAllLayouts() as $layout) {
            $elementFields[$layout->type] = array_merge(
                $elementFields[$layout->type] ?? [],
                $this->collectFieldsFromLayout($layout),
            );
        }

        return array_map(function (array $fields) {
            ksort($fields);

            return $fields;
        }, $elementFields);
    }

    /**
     * Extract field handles and their PHPDoc types from a field layout.
     *
     * @return array<string, string>
     */
    private function collectFieldsFromLayout(FieldLayout $layout): array
    {
        $fields = [];

        foreach ($layout->getCustomFields() as $field) {
            $fields[$field->handle] ??= $this->resolvePhpType($field);
        }

        foreach ($layout->getGeneratedFields() as $generatedField) {
            $handle = $generatedField['handle'] ?? '';
            if ($handle !== '') {
                $fields[$handle] ??= 'string|null';
            }
        }

        ksort($fields);

        return $fields;
    }

    /**
     * Resolve the PHPDoc type for a field, using entry type stubs for Matrix fields.
     */
    private function resolvePhpType(FieldInterface $field): string
    {
        if ($field instanceof Matrix) {
            return $this->resolveMatrixPhpType($field);
        }

        return $this->normalizePhpType($field::phpType());
    }

    /**
     * Resolve the PHPDoc type for a Matrix field using its configured entry types.
     */
    private function resolveMatrixPhpType(Matrix $field): string
    {
        $entryTypes = $field->getEntryTypes();

        if ($entryTypes === []) {
            return $this->normalizePhpType($field::phpType());
        }

        $entryTypeClasses = collect($entryTypes)
            ->map(fn ($entryType) => '\\CraftCms\\Cms\\Entry\\Elements\\'.$this->normalizeHandle($entryType->handle))
            ->sort()
            ->implode('|');

        return sprintf(
            '\\%s<%s>|\\%s<%s>',
            EntryQuery::class,
            $entryTypeClasses,
            ElementCollection::class,
            $entryTypeClasses,
        );
    }

    /**
     * Normalize a PHP type string for PHPDoc.
     */
    private function normalizePhpType(string $type): string
    {
        $types = array_map(function (string $t) {
            $t = trim($t, ' \\');

            if (preg_match('/^(self|static|bool|boolean|int|integer|float|double|string|array|object|callable|callback|iterable|resource|null|mixed|void)(\[\])?$/i', $t)) {
                return $t;
            }

            return '\\'.$t;
        }, explode('|', $type));

        return implode('|', $types);
    }

    /**
     * Shorten all FQCNs in type strings and return the import map.
     *
     * Modifies the passed arrays in-place, replacing FQCNs with short class names.
     *
     * @param  array<string, array<string, string>>  ...$fieldGroups
     * @return array<string, string> FQCN → short name
     */
    private function shortenTypes(array &...$fieldGroups): array
    {
        // Collect all FQCNs from type strings
        $fqcns = [];
        foreach ($fieldGroups as $group) {
            foreach ($group as $fields) {
                foreach ($fields as $type) {
                    preg_match_all('/\\\\[A-Za-z_][A-Za-z0-9_\\\\]+/', $type, $matches);
                    foreach ($matches[0] as $match) {
                        $fqcns[ltrim($match, '\\')] = true;
                    }
                }
            }
        }

        if ($fqcns === []) {
            return [];
        }

        // Build import map: FQCN → short name
        // If short names conflict, keep the FQCN as-is (don't import)
        $shortNameCounts = [];
        foreach (array_keys($fqcns) as $fqcn) {
            $shortNameCounts[class_basename($fqcn)][] = $fqcn;
        }

        $importMap = [];
        foreach ($shortNameCounts as $shortName => $matchingFqcns) {
            if (count($matchingFqcns) === 1) {
                $importMap[$matchingFqcns[0]] = $shortName;
            }
        }

        // Replace FQCNs in all type strings (longest first to avoid partial replacements)
        $replacements = [];
        foreach ($importMap as $fqcn => $shortName) {
            $replacements['\\'.$fqcn] = $shortName;
        }
        uksort($replacements, fn (string $a, string $b) => strlen($b) <=> strlen($a));

        foreach ($fieldGroups as &$group) {
            foreach ($group as &$fields) {
                foreach ($fields as &$type) {
                    $type = strtr($type, $replacements);
                }
            }
        }

        return $importMap;
    }

    /**
     * Collect the use imports needed for a namespace block based on the short names referenced by its classes.
     *
     * @param  list<array{className: string, fields: array<string, string>, extends?: string, see?: string}>  $classes
     * @param  array<string, string>  $importMap  FQCN → short name
     * @return list<string>
     */
    private function collectImportsForNamespace(array $classes, array $importMap, string $namespace): array
    {
        $usedShortNames = [];
        foreach ($classes as $class) {
            foreach ($class['fields'] as $type) {
                // Split on non-word characters to find all identifiers (handles generics, unions)
                foreach (preg_split('/[^A-Za-z0-9_]+/', $type) as $token) {
                    if ($token !== '') {
                        $usedShortNames[$token] = true;
                    }
                }
            }
        }

        $imports = [];
        foreach ($importMap as $fqcn => $shortName) {
            if (! isset($usedShortNames[$shortName])) {
                continue;
            }

            // Don't import classes that belong to the current namespace
            $fqcnNamespace = substr($fqcn, 0, (int) strrpos($fqcn, '\\'));
            if ($fqcnNamespace === $namespace) {
                continue;
            }

            $imports[] = $fqcn;
        }

        sort($imports);

        return $imports;
    }
}
