import {writeFileSync} from 'fs';
import {dirname, resolve} from 'path';
import {fileURLToPath} from 'url';
import {stops, lightTheme, darkTheme} from '../src/styles/color-definitions.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUT_FILE = resolve(ROOT, 'src/styles/shared/accessible-colors.css');

/**
 * Returns an array of color variable declarations
 */
function getVariableDeclarations(color, modifier = '') {
  const { values } = color;

  return values
    .map((value, index) => modifier ? `  --color-${modifier}-${color.name}-${stops[index]}: ${value.value};` : `  --color-${color.name}-${stops[index]}: ${value.value};`);
}

const lines = [
  '/* Auto-generated by scripts/generate-accessible-palette.js — do not edit manually */\n:root,\n:host {',
];

for (const color of lightTheme.contrastColors) {
  if (!color.values) continue;

  const lightThemeVariables = getVariableDeclarations(color);
  const staticVariables = getVariableDeclarations(color, 'static');
  lines.push(lightThemeVariables.join('\n'));
  lines.push(staticVariables.join('\n'));
}

lines.push('}\n');

lines.push("[data-theme='dark'] {");

for (const color of darkTheme.contrastColors) {
  if (!color.values) continue;

  const darkThemeVariables = getVariableDeclarations(color);
  lines.push(darkThemeVariables.join('\n'));
}

lines.push('}\n');

writeFileSync(OUT_FILE, lines.join('\n'));
console.log(`Generated ${OUT_FILE}`);
